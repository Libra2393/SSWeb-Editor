#!/usr/bin/env python3
"""Builds the "Item flags" and "Story flag table" tabs from the flag tables.

Every field is a plain flag reference ({"type": "itemflag", "flag": n}); the editor fills in the label from the
table's name, so naming a flag in defs/flags/*.json and re-running this keeps the tabs in sync:

    python3 tools/flag_tabs.py
"""
import json
from pathlib import Path

DEFS = Path(__file__).resolve().parent.parent / "defs"


def load(name):
    return json.loads((DEFS / "flags" / name).read_text())


def real(table):
    return [(n, e) for n, e in enumerate(table["flags"]) if e and e[0] != 255]


def named(e):
    return len(e) > 3 and e[3] and not e[3].startswith("(not implemented")


def ref(kind, n):
    return {"id": f"f{n}", "type": f"{kind}flag", "flag": n}


def write(name, section):
    (DEFS / name).write_text(json.dumps(section, indent=2, ensure_ascii=False) + "\n")


def item_tab():
    t = real(load("itemflags.json"))
    bugs = range(0x1B9, 0x1C5)
    materials = range(0x1A5, 0x1B5)
    groups = [
        ("Items and upgrades", [n for n, e in t if e[2] == 1 and named(e)], 3),
        ("Bugs (count)", [n for n, e in t if n in bugs], 3),
        ("Materials (count)", [n for n, e in t if n in materials], 3),
        ("Other named counters", [n for n, e in t if e[2] > 1 and named(e) and n not in bugs and n not in materials], 3),
        ("Unnamed flags", [n for n, e in t if e[2] == 1 and not named(e)], 6),
        ("Unnamed counters", [n for n, e in t if e[2] > 1 and not named(e)], 6),
    ]
    write("item-flags.json", {
        "id": "itemflags",
        "title": "Item flags",
        "scope": "slot",
        "layout": "flags",
        "description": "Every item flag and counter in the game's ItemflagManager table, indexed by item number. "
                       "Names are the game's own item names; counters are named after the zeldaret/ss decompilation. "
                       "A set one-bit flag means the item has been obtained at least once. "
                       "Generated by tools/flag_tabs.py.",
        "groups": [{"title": f"{title} ({len(ns)})", "columns": cols, "fields": [ref("item", n) for n in ns]}
                   for title, ns, cols in groups if ns],
    })


def story_tab():
    t = real(load("storyflags.json"))
    groups = []
    for lo in range(0, max(n for n, _ in t) + 1, 100):
        ns = [n for n, _ in t if lo <= n < lo + 100]
        if ns:
            groups.append({"title": f"Story flags {lo}–{lo + 99}", "columns": 2,
                           "fields": [ref("story", n) for n in ns]})
    write("story-flag-table.json", {
        "id": "storytable",
        "title": "Story flag table",
        "scope": "slot",
        "layout": "flags",
        "description": "Every story flag in the game's StoryflagManager table by number, labelled from the community "
                       "flag list where a name is known. The Story flags tab keeps the hand-picked WiiKing2 view. "
                       "Generated by tools/flag_tabs.py.",
        "groups": groups,
    })


OBJECT_WORDS = {
    "TBox": "chest", "Soil": "dig spot", "Item": "item on the ground", "SwAreaT": "area trigger",
    "EvntTag": "event trigger", "PushBlk": "push block", "ScChang": "exit", "demo01": "cutscene object",
    "chest": "closet or wardrobe", "Chandel": "chandelier",
}
# Uses that change the flag say more about it than uses that only read it.
ROLE_RANK = ["set when opened", "set when collected", "set when dug up", "set when pushed into place",
             "set when the closet/wardrobe is opened", "set when the chandelier falls", "set by the event",
             "set on entering the area", "unset by the event", "unset on entering the area", "makes it appear",
             "makes the NPC appear", "makes the NPC leave", "triggers the event", "needed for this exit",
             "event condition or result", "set by the event (if in this area)", "checked by the event (if in this area)"]


def describe(use):
    stage, room, layer, obj, role = use
    if obj == "Event":
        return f"{role}: event {stage} ({room})"
    where = f"{stage}" + (f" room {room}" if room != "stage" else "") + (f", layer {layer}" if layer not in (None, 0) else "")
    return f"{role}: {OBJECT_WORDS.get(obj, obj)} ({where})"


def rank(use):
    role = use[4]
    return ROLE_RANK.index(role) if role in ROLE_RANK else len(ROLE_RANK)


def scene_tab():
    scenes = load("sceneflags.json")["scenes"]
    usage = load("flag-usage.json")["scene"]
    by_scene = {}
    for key, uses in usage.items():
        scene, flag = (int(x) for x in key.split("/"))
        if flag >= 128:  # 128 and up are the temporary flags that reset on leaving an area; not stored per area
            continue
        by_scene.setdefault(scene, []).append((flag, sorted(uses, key=rank)))
    groups = []
    for name, idx in sorted(scenes.items(), key=lambda kv: kv[1]):
        flags = sorted(by_scene.get(idx, []))
        if not flags:
            continue
        fields = []
        for flag, uses in flags:
            lines = list(dict.fromkeys(describe(u) for u in uses))
            fields.append({"id": f"s{idx}f{flag}", "type": "sceneflag", "scene": name, "flag": flag,
                           "label": f"{flag}: {lines[0]}",
                           "description": "; ".join(lines[:8]) + (f"; and {len(lines) - 8} more" if len(lines) > 8 else "")})
        groups.append({"title": f"{name} ({len(fields)} located)", "columns": 1, "fields": fields})
    write("scene-flags.json", {
        "id": "sceneflags",
        "title": "Scene flags",
        "scope": "slot",
        "layout": "flags",
        "description": "Every scene flag that the game's stage data or event flows use, per area, described by the object "
                       "or event that sets or checks it (from defs/flags/flag-usage.json, built from your own game data by "
                       "tools/romfs-flag-index.mjs). Flags only read by an event are the least certain. Flags the game's "
                       "code sets directly aren't listed, nor flags numbered 128 and up, which are temporary flags that reset "
                       "when Link leaves an area. Generated by tools/flag_tabs.py.",
        "groups": groups,
    })


if __name__ == "__main__":
    item_tab()
    story_tab()
    scene_tab()
    print("wrote defs/item-flags.json, defs/story-flag-table.json and defs/scene-flags.json")
